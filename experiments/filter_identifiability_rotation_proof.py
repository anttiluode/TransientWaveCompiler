"""Algebraic proof/microscope for the exact v0.6 (2,5) realization alias.

The failed m25 direction is generated by an internal orthogonal rotation of
resonators 2 and 4.  Because the explicit-port model has identity ``U`` on the
resonator subspace and port damping only on source/load, this similarity
transformation leaves all port S parameters invariant while redistributing
coupling-matrix entries.

This is a post-hoc mechanism proof, not a qualifying benchmark.
"""
from __future__ import annotations

import json

import numpy as np

from published_cross_coupled_filter_v03 import OMEGA, PARAMETERS
from transientwave.coupled_resonator_filter import matrix_from_parameters
from transientwave.identifiability import _explicit_port_lossy_channels_with_derivatives


VALUES = np.array(
    [
        1.0200565592719817,
        -0.8644024611067477,
        0.7486562052179283,
        -0.8786320205338013,
        1.020359910890014,
        -0.1687616053091747,
        0.0004825375987860725,
    ],
    dtype=float,
)
LOSS = 0.020037341295245672


def rotation_24(theta: float) -> np.ndarray:
    r = np.eye(6)
    c = float(np.cos(theta))
    s = float(np.sin(theta))
    # Internal orthogonal change of basis on resonators 2 and 4.
    r[2, 2] = c
    r[2, 4] = s
    r[4, 2] = -s
    r[4, 4] = c
    return r


def port_response(m: np.ndarray):
    response, _deriv, _loss = _explicit_port_lossy_channels_with_derivatives(
        m, OMEGA, [], LOSS, ("s11", "s21", "s22")
    )
    return response


def main() -> None:
    m = matrix_from_parameters(6, PARAMETERS, VALUES)
    m4l = float(m[4, 5])

    # Unit m25 tangent: choose generator so delta M[2,5] = +1.
    k = np.zeros((6, 6), dtype=float)
    k[2, 4] = 1.0 / m4l
    k[4, 2] = -1.0 / m4l
    delta = k @ m - m @ k

    expected = {
        "m12": float(delta[1, 2]),
        "m23": float(delta[2, 3]),
        "m34": float(delta[3, 4]),
        "m14": float(delta[1, 4]),
        "m25": float(delta[2, 5]),
    }

    # The normalized-frequency and port damping matrices are invariant under
    # this internal rotation, which is the structural reason the entire port
    # response is invariant.
    u = np.eye(6)
    u[0, 0] = 0.0
    u[5, 5] = 0.0
    q = np.zeros((6, 6))
    q[0, 0] = 1.0
    q[5, 5] = 1.0
    comm_u = float(np.linalg.norm(k @ u - u @ k))
    comm_q = float(np.linalg.norm(k @ q - q @ k))

    base = port_response(m)
    finite_checks = []
    for theta in (0.01, 0.10, 0.35, -0.22):
        r = rotation_24(theta)
        rotated = r @ m @ r.T
        resp = port_response(rotated)
        max_error = max(
            float(np.max(np.abs(resp[ch] - base[ch])))
            for ch in ("s11", "s21", "s22")
        )
        finite_checks.append(
            {
                "theta_rad": float(theta),
                "m25": float(rotated[2, 5]),
                "m4L": float(rotated[4, 5]),
                "max_port_response_abs_error": max_error,
            }
        )

    # Why R2/R4 perturbations break the gauge but R1/R3 do not: diagonal
    # physical-coordinate stamps for nodes 1/3 commute with K; 2/4 do not.
    detuning_commutators = {}
    for node in range(1, 5):
        d = np.zeros((6, 6))
        d[node, node] = 1.0
        detuning_commutators[f"R{node}"] = float(np.linalg.norm(k @ d - d @ k))

    out = {
        "experiment": "filter-identifiability-rotation-proof",
        "qualifying_benchmark": False,
        "source": "v0.6 case 4303 / start A compensated matrix",
        "generator": {
            "mixed_resonators": [2, 4],
            "K24": float(k[2, 4]),
            "K42": float(k[4, 2]),
        },
        "unit_m25_tangent_entries": expected,
        "commutator_norm_with_U": comm_u,
        "commutator_norm_with_q": comm_q,
        "finite_rotation_invariance": finite_checks,
        "unit_detuning_commutator_norms": detuning_commutators,
        "interpretation": (
            "R2/R4 detunings anchor the coordinates mixed by the gauge; "
            "R1/R3 detunings commute with it and cannot break this realization ambiguity."
        ),
    }
    print(json.dumps(out, indent=2))
    with open("filter-identifiability-rotation-proof.json", "w", encoding="utf-8") as f:
        json.dump(out, f, indent=2)
        f.write("\n")


if __name__ == "__main__":
    main()
